# ---------------- FETCH IMAGE FROM PEXELS ----------------
def fetch_image_from_pexels(query):
    try:
        headers = {"Authorization": PEXELS_API_KEY}
        params = {"query": query, "per_page": 1}

        response = requests.get(
            "https://api.pexels.com/v1/search",
            headers=headers,
            params=params,
            timeout=10
        )

        data = response.json()

        if data.get("photos"):
            image_url = data["photos"][0]["src"]["large"]
            img_response = requests.get(image_url, timeout=10)
            return BytesIO(img_response.content)

    except Exception as e:
        print("Pexels Error:", e)

    return None


# ---------------- MAIN FUNCTION ----------------
def generate_pdf_ppt():
    try:
        title_input = request.form.get("title", "Presentation")
        owner = request.form.get("owner", "Generated by App")
        font_size = int(request.form.get("font", 24))
        points_per_slide = int(request.form.get("points", 3))
        theme = request.form.get("theme", "gray")

        if "file" not in request.files:
            return "No file uploaded"

        file = request.files["file"]
        if file.filename == "":
            return "No selected file"

        filename = secure_filename(file.filename)
        filepath = os.path.join(UPLOAD_FOLDER, filename)
        file.save(filepath)

        # -------- EXTRACT PDF TEXT --------
        full_text = ""
        with pdfplumber.open(filepath) as pdf:
            for page in pdf.pages:
                text = page.extract_text()
                if text:
                    full_text += text + "\n"

        if not full_text.strip():
            return "Could not extract text from PDF"

        # Clean text
        full_text = re.sub(r'http\S+|www\S+', '', full_text)
        full_text = re.sub(r'\[[0-9]+\]', '', full_text)
        full_text = re.sub(r'\([0-9]{4}\)', '', full_text)
        full_text = re.sub(r'\s+', ' ', full_text).strip()

        sentences = re.split(r'(?<=[.!?])\s+', full_text)
        sentences = [s.strip() for s in sentences if 50 < len(s.strip()) < 500]

        if not sentences:
            return "Not enough meaningful content found"

                # -------- EXTRACT IMAGES FROM PDF --------
        extracted_images = []

        with pdfplumber.open(filepath) as pdf:
            for page in pdf.pages:
                for img in page.images:
                    try:
                        x0, top, x1, bottom = img["x0"], img["top"], img["x1"], img["bottom"]
                        cropped = page.crop((x0, top, x1, bottom))
                        img_obj = cropped.to_image(resolution=150)
                        img_bytes = BytesIO()
                        img_obj.save(img_bytes, format="PNG")
                        img_bytes.seek(0)
                        extracted_images.append(img_bytes)
                    except:
                        pass

        prs = Presentation()

        # -------- THEME FUNCTION --------
        def apply_theme(slide):
            colors = {
                "mint": (220, 255, 220),
                "peach": (255, 229, 180),
                "lavender": (243, 229, 245),
                "sky": (225, 245, 254),
                "gray": (240, 240, 240)
            }
            r, g, b = colors.get(theme, (255, 255, 255))
            fill = slide.background.fill
            fill.solid()
            fill.fore_color.rgb = RGBColor(r, g, b)

        # -------- PAGE NUMBER --------
        def add_page_number(slide, number):
            box = slide.shapes.add_textbox(Inches(9), Inches(6.8), Inches(1), Inches(0.3))
            tf = box.text_frame
            tf.clear()
            p = tf.paragraphs[0]
            p.text = str(number)
            p.font.size = Pt(12)
            p.font.bold = True
            p.font.color.rgb = RGBColor(120, 120, 120)

        # ===============================
        # -------- TITLE SLIDE ----------
        # ===============================

        slide = prs.slides.add_slide(prs.slide_layouts[6])
        apply_theme(slide)

        slide_width = prs.slide_width
        slide_height = prs.slide_height

        # -------- TITLE (TOP CENTER) --------
        title_box = slide.shapes.add_textbox(
            0,
            slide_height * 0.05,     # near top
            slide_width,
            slide_height * 0.15
        )

        tf = title_box.text_frame
        tf.clear()
        p = tf.paragraphs[0]
        p.text = title_input
        p.font.size = Pt(44)
        p.font.bold = True
        p.alignment = PP_ALIGN.CENTER


        # -------- CENTER IMAGE --------
        img_stream = fetch_image_from_pexels(title_input)
        if img_stream:
            img_width = Inches(5)
            img_height = Inches(3)

            left = (slide_width - img_width) / 2
            top = (slide_height - img_height) / 2

            slide.shapes.add_picture(
                img_stream,
                left,
                top,
                width=img_width,
                height=img_height
            )


        # -------- PRESENTED BY (BOTTOM RIGHT) --------
        owner_box = slide.shapes.add_textbox(
            slide_width * 0.60,
            slide_height * 0.90,
            slide_width * 0.35,
            slide_height * 0.08
        )

        owner_tf = owner_box.text_frame
        owner_tf.clear()
        p = owner_tf.paragraphs[0]
        p.text = f"Presented by - {owner}"
        p.alignment = PP_ALIGN.RIGHT
        p.font.size = Pt(20)
        p.font.bold = True


        slide_number = 1
        slide_index = 0


        # ===============================
        # -------- CONTENT SLIDES -------
        # ===============================
        for i in range(0, len(sentences), points_per_slide):

            chunk = sentences[i:i + points_per_slide]
            if not chunk:
                continue

            slide = prs.slides.add_slide(prs.slide_layouts[1])
            apply_theme(slide)

            # Structured titles
            if slide_index < len(COMMON_TITLES):
                slide.shapes.title.text = COMMON_TITLES[slide_index]
            else:
                slide.shapes.title.text = f"Section {slide_index + 1}"

            slide_index += 1

            tf = slide.placeholders[1].text_frame
            tf.clear()

            for idx, sentence in enumerate(chunk):
                if idx >= 4:
                    break

                words = sentence.split()
                if len(words) > 30:
                    sentence = " ".join(words[:30]) + "..."

                p = tf.add_paragraph()
                p.text = sentence
                p.font.size = Pt(font_size)
                p.level = 0

            add_page_number(slide, slide_number)
            slide_number += 1

        # ===============================
        # -------- DIAGRAM SLIDES -------
        # ===============================

        figure_counter = 1

        for img_stream in extracted_images:

            slide = prs.slides.add_slide(prs.slide_layouts[1])
            apply_theme(slide)

            slide.shapes.title.text = f"Diagram {figure_counter}"

            img_width = Inches(6)
            img_height = Inches(4)

            left = (prs.slide_width - img_width) / 2
            top = (prs.slide_height - img_height) / 2

            try:
                slide.shapes.add_picture(
                    img_stream,
                    left,
                    top,
                    width=img_width,
                    height=img_height
                )
            except Exception as e:
                print("Image Add Error:", e)

            add_page_number(slide, slide_number)
            slide_number += 1
            figure_counter += 1

        # ===============================
        # -------- THANK YOU SLIDE ------
        # ===============================
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        apply_theme(slide)
        slide.shapes.title.text = "Thank You"
        slide.placeholders[1].text = "Questions?"
        add_page_number(slide, slide_number)

        # -------- SAVE FILE --------
        timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
        output_filename = f"generated_{timestamp}.pptx"
        output_path = os.path.join(OUTPUT_FOLDER, output_filename)
        prs.save(output_path)

        return send_file(output_path, as_attachment=True)

    except Exception as e:
        return f"Error occurred: {str(e)}"

